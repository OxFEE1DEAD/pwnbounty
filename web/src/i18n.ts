const prefixes=Object.keys(ru).filter(key=>/[ #]$/.test(key));
const storageKey='sealed-bounty/lang/1';
const originals=new WeakMap<Node,string>();
let lang:'en'|'ru'=navigator.language.toLowerCase().startsWith('ru')?'ru':'en';
try{const saved=localStorage.getItem(storageKey);if(saved==='en'||saved==='ru')lang=saved;}catch{}

export function t(value:string):string {
  if(lang==='en')return value;
  const prefix=ru[value]?undefined:prefixes.find(key=>value.startsWith(key));
  return ru[value]??(prefix?ru[prefix]+value.slice(prefix.length):value);
}
export function show(target:HTMLElement,value:string):void {target.dataset.en=value;target.textContent=t(value);}
export function applyLanguage():void {
  document.documentElement.lang=lang;
  const walker=document.createTreeWalker(document.body,NodeFilter.SHOW_TEXT);
  for(let node=walker.nextNode();node;node=walker.nextNode()){
    if(node.parentElement?.closest('[data-en],pre,textarea,script'))continue;
    const original=originals.get(node)??node.nodeValue??'';originals.set(node,original);
    const key=original.trim();if(key)node.nodeValue=original.replace(key,t(key));
  }
  for(const field of document.querySelectorAll<HTMLInputElement|HTMLTextAreaElement>('[placeholder]')){field.dataset.placeholder??=field.placeholder;field.placeholder=t(field.dataset.placeholder);}
  for(const target of document.querySelectorAll<HTMLElement>('[data-en]'))target.textContent=t(target.dataset.en!);
  const toggle=document.getElementById('lang');if(toggle)toggle.textContent=lang==='en'?'RU':'EN';
}
export function toggleLanguage():void {lang=lang==='en'?'ru':'en';try{localStorage.setItem(storageKey,lang);}catch{}applyLanguage();}
